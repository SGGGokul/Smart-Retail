import logging
from typing import Optional
import uuid

from app.schemas.assistant import AssistantChatRequest, AssistantChatResponse
from app.services.analytics_service import get_analytics_service
from app.services.rule_engine import get_rule_engine

logger = logging.getLogger("retailiq.assistant_service")


class AssistantService:
    """Answers store operations queries strictly from verified analytics and alerts telemetry.

    Does not fabricate GenAI answers; transparently states capabilities and boundaries.
    """

    def handle_chat(self, payload: AssistantChatRequest) -> AssistantChatResponse:
        """Process retail query and return verifiable answer conforming to API_CONTRACT.md."""
        message = payload.message.lower().strip()
        conv_id = payload.conversationId or f"conv-{uuid.uuid4().hex[:6]}"

        analytics_service = get_analytics_service()
        summary = analytics_service.get_summary()
        rule_engine = get_rule_engine()
        alerts = rule_engine.list_alerts()

        # Follow-up prompts suggested to user
        follow_ups = [
            "How many customers visited today?",
            "What is the average dwell time?",
            "Summarize today's alerts.",
        ]

        # 1. Customer volume / traffic queries
        if any(term in message for term in ["customer", "visitor", "traffic", "footfall", "people"]):
            if summary.todayCustomers > 0:
                answer = (
                    f"A total of {summary.todayCustomers} unique customer(s) have been detected "
                    f"today across processed video analytics streams."
                )
            else:
                answer = (
                    "No customer traffic has been recorded yet today. Upload store footage via the "
                    "Video Analytics portal to process footfall telemetry."
                )

        # 2. Dwell time queries
        elif any(term in message for term in ["dwell", "duration", "wait time", "spent", "time"]):
            if summary.avgDwellMinutes > 0:
                answer = (
                    f"The average observed customer dwell time is currently {summary.avgDwellMinutes} minutes "
                    f"based on completed video tracking jobs."
                )
            else:
                answer = (
                    "No dwell time telemetry is currently recorded. Dwell times are calculated "
                    "automatically when video analytics jobs are completed."
                )

        # 3. Shelf / Inventory queries
        elif any(term in message for term in ["shelf", "shelves", "stock", "restock", "inventory"]):
            answer = (
                "Shelf inventory monitoring via YOLO11n is currently unavailable pending specialized "
                "shelf-detection model integration in a future stage. No shelves currently need restocking."
            )

        # 4. Queue queries
        elif any(term in message for term in ["queue", "checkout", "line"]):
            answer = (
                "Checkout queue detection is currently not enabled in this stage. 0 active queues are monitored."
            )

        # 5. Alerts queries
        elif any(term in message for term in ["alert", "warning", "critical", "incident"]):
            if alerts:
                alert_summaries = "; ".join(f"[{a.severity.upper()}] {a.description}" for a in alerts[:3])
                answer = (
                    f"There are currently {len(alerts)} active alert(s) generated by the Computer Vision "
                    f"rule engine: {alert_summaries}"
                )
            else:
                answer = "There are currently no active alerts. All operational systems are normal."

        # 6. Fallback / general queries
        else:
            answer = (
                "RetailIQ Assistant is currently operating in verified analytics mode (Stage 2). "
                "RAG and generative language models are scheduled for a future stage. "
                "I can answer verified queries about customer counts, dwell times, and vision alerts."
            )

        return AssistantChatResponse(
            answer=answer,
            conversationId=conv_id,
            suggestedFollowUps=follow_ups,
        )


_assistant_service: Optional[AssistantService] = None


def get_assistant_service() -> AssistantService:
    """Singleton getter for assistant service."""
    global _assistant_service
    if _assistant_service is None:
        _assistant_service = AssistantService()
    return _assistant_service
