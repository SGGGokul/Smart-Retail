from typing import Optional
from fastapi import APIRouter, HTTPException, Query, status

from app.schemas.alerts import AlertItem, AlertsResponse, AlertUpdateRequest
from app.services.rule_engine import get_rule_engine

router = APIRouter()


@router.get(
    "",
    response_model=AlertsResponse,
    summary="List system and vision alerts",
)
async def list_alerts(
    severity: Optional[str] = Query(default=None, description="info | warning | critical"),
    acknowledged: Optional[bool] = Query(default=None, description="Filter by acknowledgment state"),
) -> AlertsResponse:
    """Lists system and vision alerts generated by the CV rule engine from PostgreSQL."""
    rule_engine = get_rule_engine()
    alerts = await rule_engine.list_alerts(severity=severity, acknowledged=acknowledged)
    total_count, unack_count = await rule_engine.count_alerts()

    return AlertsResponse(
        alerts=alerts,
        totalCount=total_count,
        unacknowledgedCount=unack_count,
    )


@router.patch(
    "/{id}",
    response_model=AlertItem,
    summary="Update alert status",
)
async def update_alert(id: str, payload: AlertUpdateRequest) -> AlertItem:
    """Updates an alert status (e.g., marks it as acknowledged) in PostgreSQL."""
    rule_engine = get_rule_engine()
    updated = await rule_engine.update_alert(id, payload)
    if updated is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Alert '{id}' was not found.",
        )
    return updated
